"""Prepare the pinned Banjo-Kazooie port without changing its checkout or reading any game ROM."""
import json
from pathlib import Path
import re
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
pin = json.loads((root / "upstream/lighthouse-baseline.json").read_text())
source = root / "build/upstream/Lighthouse"
revision = pin["sources"]["lighthouse"]["revision"]
actual = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
if actual != revision:
    raise SystemExit("The Lighthouse checkout does not match the pinned release.")
if subprocess.check_output(["git", "-C", str(source), "status", "--porcelain"], text=True).strip():
    raise SystemExit("Preserve the upstream checkout's local edits before preparing a generated copy.")
destination = root / "build/lighthouse/source"


def swap(text, old, new):
    """TEXT with OLD replaced by NEW. Fails when an upstream update changed OLD."""
    if old not in text:
        raise SystemExit(f"prepare-lighthouse.py: {old.strip()[:70]!r} is no longer in the pinned source")
    return text.replace(old, new)


# Lighthouse expects a new process for each start, but Nativecade starts it again in the same one
# (docs/GAME_SWITCHING.md). These flags only ever go one way during shutdown, so
# experiments/lighthouse/LighthouseRestart.cpp sets them back after each game.
RESETS = {
    "src/port/Game.cpp": ("NativecadeLighthouseResetGame", """\
    sGameThreadDone = false; // otherwise game-thread tasks run on the render thread
    sShutdownRequested = false;
    sSvcFn = nullptr;
    sSvcArg = nullptr;
    sParked = false;
    sTaskInterp.clear();
    sTaskReleased = true;
    sReleaseDeferred = false;"""),
    "src/port/OS/OS_Threads.cpp": ("NativecadeLighthouseResetThreads", """\
    std::lock_guard<std::mutex> lock(sTableMutex);
    sThreads.clear(); // OS_JoinDecompThreads joined or detached every worker
    sExitRequested = false; // otherwise every decomp thread leaves at once"""),
    "src/port/OS/OS_RCP.cpp": ("NativecadeLighthouseResetRcp", """\
    // A task still pending at Quit points into game memory, which is reset before the next start.
    sPendingTask = nullptr;
    sYieldPending = false;
    sResumePending = false;
    sStatus = 0;"""),
    "src/port/OS/OS_Timer.cpp": ("NativecadeLighthouseResetTimers", """\
    std::lock_guard<std::mutex> lock(sMutex);
    sTimers.clear();
    sWorkerStarted = false; // otherwise no timer fires again
    sStop = false;"""),
}


def adapt(relative, text):
    if relative in RESETS:
        name, body = RESETS[relative]
        text += f'\n// Generated by scripts/prepare-lighthouse.py for Nativecade.\nextern "C" void {name}(void) {{\n{body}\n}}\n'
    if relative == "lib/ultralib/gu/gu_pc.c":
        # Without GBI_FLOATS, Mtx holds the N64's fixed-point matrix, as in the other gu functions here.
        text = swap(text, "void guMtxIdent(Mtx* m) {\n    guMtxIdentF(m->mf);\n}",
                    "void guMtxIdent(Mtx* m) {\n    float mf[4][4];\n    guMtxIdentF(mf);\n    guMtxF2L(mf, m);\n}")
    if relative == "src/port/Controller/ControlSchemes.cpp":
        # The shared libultraship reads 32-bit button masks (CONTROLLERBUTTONS_T), as Shipwright needs.
        text = swap(text, "uint16_t held = 0;", "CONTROLLERBUTTONS_T held = 0;")
        text = swap(text, "uint16_t& otherHeld", "CONTROLLERBUTTONS_T& otherHeld")
        text = swap(text, "uint16_t otherHeld = 0;", "CONTROLLERBUTTONS_T otherHeld = 0;")
    if relative == "src/port/Enhancements/Trackers/DisplayOverlay.cpp":
        # Upstream reaches the header through its libultraship submodule folder.
        text = swap(text, "#include <libultraship/include/libultraship/libultra/gbi.h>", "#include <libultraship/libultra/gbi.h>")
    if relative == "src/port/Engine.cpp":
        # Nativecade prepares bk.o2r before the game starts, so the first-run extractor never runs.
        text = swap(text, "    instance->RunExtract(argc, argv);\n", "")
        # An Apple TV app can't replace its own process.
        text = swap(text, "#elif defined(__linux__) || defined(__APPLE__)\n    execv(", "#elif defined(__linux__)\n    execv(")
    return text


# The game's code and headers, and the script that generates the Flag Tracer's name tables.
# config.yml, assets/ and port/ are packed by prepare-lighthouse-resources.py.
originals = [path for folder in ("include", "lib", "src") for path in (source / folder).rglob("*")]
for original in originals + [source / "cmake/GenerateFlagNames.cmake"]:
    relative = original.relative_to(source).as_posix()
    if not original.is_file() or relative.startswith("src/unused/"):
        continue
    target = destination / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if original.suffix not in {".c", ".cpp", ".h", ".hpp"}:
        shutil.copy2(original, target)
        continue
    text = adapt(relative, original.read_text(errors="surrogateescape"))
    # Preserve timestamps when an adapter hasn't changed, keeping rebuilds small.
    if not target.exists() or target.read_text(errors="surrogateescape") != text:
        target.write_text(text, errors="surrogateescape")

# Upstream's CMake writes the version strings from src/port/build.c.in, naming each patch release
# with the NATO alphabet ("Montauk Charlie" is 1.2.2).
cmake = (source / "CMakeLists.txt").read_text()
nato = re.findall(r'"(\w+)"', re.search(r"set\(NATO_PHONETIC_ALPHABET(.*?)\)", cmake, re.S)[1])
series = re.search(r'set\(PROJECT_BUILD_NAME "(\w+) \$\{PROJECT_PATCH_WORD\}"', cmake)[1]
major, minor, patch = pin["release"].split(".")
values = {"PROJECT_BUILD_NAME": f"{series} {nato[int(patch)]}", "PROJECT_TEAM": "",
          "CMAKE_PROJECT_VERSION_MAJOR": major, "CMAKE_PROJECT_VERSION_MINOR": minor,
          "CMAKE_PROJECT_VERSION_PATCH": patch, "CMAKE_PROJECT_GIT_BRANCH": "",
          "CMAKE_PROJECT_GIT_COMMIT_HASH": revision[:7], "CMAKE_PROJECT_GIT_COMMIT_TAG": pin["release"]}
build = re.sub(r"@(\w+)@", lambda match: values[match[1]], (source / "src/port/build.c.in").read_text())
target = destination / "src/port/build.c"
if not target.exists() or target.read_text() != build:
    target.write_text(build)
print(f"Prepared Lighthouse {pin['release']} in {destination}")
