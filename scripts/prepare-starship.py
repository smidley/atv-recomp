"""Prepare the pinned Star Fox 64 port without changing its checkout or reading any game ROM."""
import json
from pathlib import Path
import re
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
pin = json.loads((root / "upstream/starship-baseline.json").read_text())
source = root / "build/upstream/Starship"
actual = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
if actual != pin["sources"]["starship"]["revision"]:
    raise SystemExit("The Starship checkout does not match the pinned release.")
if subprocess.check_output(["git", "-C", str(source), "status", "--porcelain"], text=True).strip():
    raise SystemExit("Preserve the upstream checkout's local edits before preparing a generated copy.")
destination = root / "build/starship/source"
shutil.copytree(source, destination, dirs_exist_ok=True,
    ignore=shutil.ignore_patterns(".git", "src", "libultraship", "tools"))
# The shared runtime's CVar names are a configuration ABI.
mapping = {
    "gVsyncEnabled": "gSettings.VsyncEnabled",
    "gInternalResolution": "gSettings.InternalResolution",
    "gMSAAValue": "gSettings.MSAAValue",
    "gControlNav": "gSettings.ControlNav",
    "gTextureFilter": "gSettings.TextureFilter",
    "gSdlWindowedFullscreen": "gSettings.SdlWindowedFullscreen",
    "gEnableMultiViewports": "gSettings.EnableMultiViewports",
    "gInterpolationFPS": "gSettings.InterpolationFPS",
    "gMatchRefreshRate": "gSettings.MatchRefreshRate",
    "gLowResMode": "gSettings.LowResMode",
}
# Where current libultraship keeps the headers Starship includes by their older paths.
includes = {
    "Resource.h": "ship/resource/Resource.h",
    "ResourceFactoryBinary.h": "ship/resource/ResourceFactoryBinary.h",
    "ResourceFactoryXML.h": "ship/resource/ResourceFactoryXML.h",
    "ResourceManager.h": "ship/resource/ResourceManager.h",
    "DisplayList.h": "fast/resource/type/DisplayList.h",
    "Context.h": "ship/Context.h",
    "utils/binarytools/BinaryReader.h": "ship/utils/binarytools/BinaryReader.h",
    "BitConverter.h": "ship/utils/binarytools/BitConverter.h",
    "endianness.h": "ship/utils/binarytools/endianness.h",
    "StringHelper.h": "ship/utils/StringHelper.h",
    "utils/StringHelper.h": "ship/utils/StringHelper.h",
    "resourcebridge.h": "libultraship/bridge/resourcebridge.h",
    "Fast3D/interpreter.h": "fast/interpreter.h",
    "graphic/Fast3D/interpreter.h": "fast/interpreter.h",
    "Fast3D/Fast3dWindow.h": "fast/Fast3dWindow.h",
    "DisplayListFactory.h": "fast/resource/factory/DisplayListFactory.h",
    "TextureFactory.h": "fast/resource/factory/TextureFactory.h",
    "MatrixFactory.h": "fast/resource/factory/MatrixFactory.h",
    "VertexFactory.h": "fast/resource/factory/VertexFactory.h",
    "BlobFactory.h": "ship/resource/factory/BlobFactory.h",
}
# libultraship now ships Starship's event system, owned by its Context, so listeners
# reset with each game start. Its fields are capitalized and REGISTER_LISTENER takes
# the priority first; Starship's calls keep their order.
events = """#pragma once
// Generated by scripts/prepare-starship.py from libultraship's event system.
#include <stdbool.h>
#include "ship/events/EventTypes.h"
#include "libultraship/bridge/eventsbridge.h"
#undef REGISTER_LISTENER
#define REGISTER_LISTENER(eventType, callback, priority) \\
    EventSystemRegisterListener(eventType##ID, callback, priority, __FILE__, __LINE__);
// libultraship's header is often included first, through libultraship.h, so its own
// INIT_EVENT_IDS check misses PortEnhancements.c, which defines the IDs.
#undef DECLARE_EVENT
#ifdef INIT_EVENT_IDS
#define DECLARE_EVENT(eventName) EventID eventName##ID = -1;
#else
#define DECLARE_EVENT(eventName) extern EventID eventName##ID;
#endif
"""


button_names = "std::unordered_map<CONTROLLERBUTTONS_T, std::string>{ " + ", ".join(
    f'{{ BTN_{button.upper()}, "{button}" }}' for button in
    ("A", "B", "L", "R", "Z", "Start", "CLeft", "CRight", "CUp", "CDown", "DLeft", "DRight", "DUp", "DDown")) + " }"


def require(text, header):
    """TEXT with HEADER included after its first include."""
    if header in text:
        return text
    return re.sub(r'^#include .*$', lambda match: f'{match[0]}\n#include "{header}"', text, count=1, flags=re.M)


def adapt(relative, text):
    if relative == "port/hooks/impl/EventSystem.h":
        return events
    text = re.sub(r'#include\s*[<"]([^>"]+)[>"]',
                  lambda match: f'#include "{includes[match[1]]}"' if match[1] in includes else match[0], text)
    text = text.replace('#include "libultraship/src/', '#include "ship/')
    text = text.replace("->event.cancelled", "->Event.Cancelled").replace("->cancelled", "->Cancelled")
    # Without GBI_FLOATS, Mtx holds the N64's fixed-point matrix.
    text = text.replace("guMtxF2L(src->mf, dest->m);", "guMtxL2F(dest->m, src);")
    # Newer Torch also has a constructor without the modding flag; name it.
    text = text.replace("new Companion(this->mGameData, ArchiveType::O2R, false)",
                        "new Companion(this->mGameData, ArchiveType::O2R, false, false)")
    # Current libultraship owns Context and separates Fast3D GUI/backend types.
    text = text.replace('Context::GetInstance()', 'Context::GetRawInstance()')
    text = text.replace('std::shared_ptr<Ship::Context> context;', 'Ship::Context* context = nullptr;')
    text = text.replace('Ship::WindowBackend::', 'Fast::WindowBackend::')
    text = text.replace('Ship::WindowBackend', 'int32_t')
    # Texture lookup moved to Fast3D's GUI, as in Shipwright's own update.
    text = text.replace("Ship::Context::GetRawInstance()->GetWindow()->GetGui()->GetTextureByName(",
                        "std::dynamic_pointer_cast<Fast::Fast3dGui>("
                        "Ship::Context::GetRawInstance()->GetWindow()->GetGui())->GetTextureByName(")
    # The controller deck now takes button names (as in SpaghettiKart), and the audio
    # channel mode is part of AudioSettings, stereo by default.
    text = text.replace("std::make_shared<LUS::ControlDeck>(std::vector<CONTROLLERBUTTONS_T>(), defaultMappings)",
                        "std::make_shared<LUS::ControlDeck>(std::vector<CONTROLLERBUTTONS_T>(), defaultMappings, "
                        + button_names + ")")
    text = text.replace("Ship::Context::GetRawInstance()->GetConfig()->GetCurrentAudioChannelsSetting()",
                        "audioStereo")
    if "LUS::ControlDeck" in text:
        text = require(text, "libultraship/controller/controldeck/ControlDeck.h")
    # Since Torch 4e021e10, sequences are "SEQC" version 2 rather than blobs: the same size
    # and bytes, then table metadata that Starship reads from its own tables.
    blob = '"Blob", static_cast<uint32_t>(Ship::ResourceType::Blob), 0);'
    text = text.replace(blob, blob + "\n    loader->RegisterResourceFactory(std::make_shared<Ship::ResourceFactoryBinaryBlobV0>(), "
                        "RESOURCE_FORMAT_BINARY,\n                                    \"Sequence\", "
                        "static_cast<uint32_t>(SF64::ResourceType::Sequence), 2);")
    # The backend list lost its count; Metal is the last backend.
    text = text.replace("Fast::WindowBackend::WINDOW_BACKEND_COUNT", "Fast::WindowBackend::FAST3D_SDL_METAL + 1")
    if "Fast::Fast3dGui" in text:
        text = require(text, "fast/Fast3dGui.h")
    if "Fast::WindowBackend" in text:
        text = require(text, "fast/Fast3dWindow.h")
    if "Fast::ResourceType" in text:
        text = require(text, "fast/resource/ResourceType.h")
    for old, new in mapping.items():
        text = text.replace('"' + old + '"', '"' + new + '"')
    text = text.replace('"gAdvancedResolution.', '"gSettings.AdvancedResolution.')
    if relative == "port/Engine.cpp":
        # Timers and audio pacing outlive a game; a pending timer would otherwise fire
        # in the next start and change its state (StarshipRestart.cpp).
        text += ("\nextern \"C\" void NativecadeStarshipReset() {\n"
                 "    gTimerTasks.clear();\n    frames = 0;\n    countermin = 0;\n}\n")
    return text


for original in (source / "src").rglob("*"):
    if not original.is_file():
        continue
    relative = original.relative_to(source / "src").as_posix()
    target = destination / "src" / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if original.suffix not in {".c", ".cpp", ".h"}:
        shutil.copy2(original, target)
        continue
    text = adapt(relative, original.read_text())
    # Preserve timestamps when an adapter hasn't changed, keeping rebuilds small.
    if not target.exists() or target.read_text() != text:
        target.write_text(text)
print(f"Prepared Starship {pin['release']} in {destination}")
