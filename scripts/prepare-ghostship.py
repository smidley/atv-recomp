"""Prepare the pinned Super Mario 64 port without changing its checkout or reading any game ROM."""
import json
from pathlib import Path
import re
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
pin = json.loads((root / "upstream/ghostship-baseline.json").read_text())
source = root / "build/upstream/Ghostship"
revision = pin["sources"]["ghostship"]["revision"]
actual = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
if actual != revision:
    raise SystemExit("The Ghostship checkout does not match the pinned release.")
if subprocess.check_output(["git", "-C", str(source), "status", "--porcelain"], text=True).strip():
    raise SystemExit("Preserve the upstream checkout's local edits before preparing a generated copy.")
destination = root / "build/ghostship/source"

# Ghostship 3.0.0 was written for a libultraship branch whose subsystems are Context components.
# Nativecade's shared libultraship builds them in Context::Init, as SpaghettiKart's engine does.
engine = """GameEngine::GameEngine() : dictionary(nullptr) {
    // Generated by scripts/prepare-ghostship.py for Nativecade's shared libultraship.
    this->context = Ship::Context::CreateUninitializedInstance("Ghostship", "sm64", "ghostship.cfg.json");
    ShipCompat::SetContext(this->context);
    this->context->InitConfiguration();
    this->context->InitConsoleVariables();
    RecompTVInitializePerformanceDefaults(); // the control deck reads these settings

    assets_path = Ship::Context::LocateFileAcrossAppDirs("ghostship.o2r");
    portArchiveVersionMatch = std::filesystem::exists(assets_path);
    auto controlDeck = std::make_shared<LUS::ControlDeck>();
    this->context->InitResourceManager({ assets_path }, {}, 3);
    this->context->InitConsole();
    gsFast3dWindow = std::make_shared<Fast::Fast3dWindow>(std::vector<std::shared_ptr<Ship::GuiWindow>>({}));
    this->context->Init({ assets_path }, {}, 3, { 32000, 512, 1100 }, gsFast3dWindow, controlDeck);

#if (_DEBUG)
    auto defaultLogLevel = spdlog::level::debug;
#else
    auto defaultLogLevel = spdlog::level::info;
#endif
    auto logLevel =
        static_cast<spdlog::level::level_enum>(CVarGetInteger(CVAR_DEVELOPER_TOOLS("LogLevel"), defaultLogLevel));
    spdlog::set_level(logLevel);
    spdlog::flush_on(logLevel);

    GhostshipGui::SetupMenu();
"""

