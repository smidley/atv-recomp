def swap(text, old, new):
    """TEXT with OLD replaced by NEW. Fails when an upstream update changed OLD."""
    if old not in text:
        raise SystemExit(f"prepare-ghostship.py: {old.strip()[:70]!r} is no longer in the pinned source")
    return text.replace(old, new)


def adapt(relative, text):
    if relative == "src/port/ShipCompat.cpp":
        return compat
    if relative == "src/port/ui/GhostshipShaderMenu.cpp":
        # The shared libultraship has no shader packs.
        return '#include "GhostshipMenu.h"\n\nvoid GhostshipGui::GhostshipMenu::AddMenuShaderSettings() {\n}\n'
    # GUI elements initialize in InitElement() rather than a component's OnInit(json).
    text = text.replace("void OnInit(const nlohmann::json& initArgs = nlohmann::json::object()) override;",
                        "void InitElement() override;")
    text = re.sub(r"void ((?:\w+::)*\w+)::OnInit\(const nlohmann::json& initArgs\) \{", r"void \1::InitElement() {", text)
    text = re.sub(r"\n[ \t]*(?:Ship::)?GuiWindow::OnInit\(initArgs\);", "", text)
    text = text.replace("Ship::Menu::OnInit(initArgs);", "Ship::Menu::InitElement();")
    # A component's OnInit() has a default; InitElement() doesn't, so windows without one get it empty.
    for match in reversed(list(re.finditer(r"class \w+(?: final)? : public (?:Ship::)?GuiWindow \{", text))):
        depth = 0
        for end in range(match.end() - 1, len(text)):
            depth += {"{": 1, "}": -1}.get(text[end], 0)
            if depth == 0:
                break
        if "InitElement" not in text[match.end():end]:
            text = text[:match.end()] + "\n  public:\n    void InitElement() override {\n    }\n\n  private:" + text[match.end():]
    # GUI textures take a palette path before the tint.
    text = re.sub(r"LoadGuiTexture\(([^,()]+), ([^,()]+), ImVec4", r'LoadGuiTexture(\1, \2, "", ImVec4', text)
    # Without GBI_FLOATS, Mtx holds the N64's fixed-point matrix; interpolation still uses floats.
    if relative == "src/port/interpolation/matrix.c":
        text = swap(text, "guMtxF2L(src->mf, dest->mf);", "guMtxL2F(dest->mf, src);")
    if relative == "src/port/interpolation/FrameInterpolation.cpp":
        text = swap(text, "guOrtho(new_replacement(new_op.ortho.m), ", "guOrthoF(new_replacement(new_op.ortho.m)->mf, ")
    if relative == "src/port/ui/TouchControls.cpp":
        # Apple TV has no touchscreen, though the build uses Ghostship's iOS code.
        text = swap(text, "#if defined(PLATFORM_IOS) || defined(__IOS__) || defined(__ANDROID__)\n#define TOUCH_CONTROLS_DEFAULT 1",
                    "#if (defined(PLATFORM_IOS) || defined(__IOS__) || defined(__ANDROID__)) && !defined(RECOMPTV_TVOS)\n"
                    "#define TOUCH_CONTROLS_DEFAULT 1")
    if relative == "src/port/ui/GhostshipGui.cpp":
        # The shared libultraship's debugger window finds the window and debugger itself.
        text = re.sub(r'(std::make_shared<LUS::GfxDebuggerWindow>\(CVAR_WINDOW\("GfxDebugger"\), "Gfx Debugger"),[^;]*\);',
                      r"\1);", text)
    if relative == "src/port/ShipCompat.h":
        text = swap(text, "class FileDrop;", "class FileDropMgr;")
        text = swap(text, "std::shared_ptr<Ship::FileDrop> GetFileDropMgr();", "std::shared_ptr<Ship::FileDropMgr> GetFileDropMgr();")
        text = swap(text, "void SetContext(std::shared_ptr<Ship::Context> context);", "void SetContext(Ship::Context* context);")
        text = swap(text, "std::shared_ptr<Ship::Context> GetContext();", "Ship::Context* GetContext();")
    if relative == "src/port/Engine.h":
        text = swap(text, "std::shared_ptr<Ship::Context> context;", "Ship::Context* context = nullptr;")
    if relative == "src/port/Engine.cpp":
        for header in ("ship/log/Logger.h", "ship/thread/ThreadPool.h", "ship/window/FileDrop.h", "ship/events/Events.h"):
            text = swap(text, f"#include <{header}>\n", "")
        text = swap(text, '#include "Engine.h"\n', '#include "Engine.h"\n#include "AppleTVPerformance.h"\n')
        start = text.index("GameEngine::GameEngine() : dictionary(nullptr) {")
        end = text.index("\n    if (portArchiveVersionMatch) {", start)
        text = text[:start] + engine + text[end:]
        text = swap(text, "static void SetupScriptLoader(std::shared_ptr<Ship::Context> context) {",
                    "static void SetupScriptLoader(Ship::Context* context) {")
        # Context::Init already created the file drop handler and audio.
        text = swap(text, """    auto fileDropMgr = std::make_shared<Ship::FileDrop>(gsFast3dWindow);
    context->GetChildren().Add(fileDropMgr);
    fileDropMgr->Init();
""", "")
        text = swap(text, """    auto audio = std::make_shared<Ship::Audio>(
        Ship::AudioSettings{ .SampleRate = 32000, .SampleLength = 512, .DesiredBuffered = 1100 },
        ShipCompat::GetConfig());
    context->GetChildren().Add(audio);
    AudioSetAudioComponent(audio);
    audio->Init();
""", "")
        # Like upstream's Switch build, interpolate matrices but not display-list replacements.
        text = swap(text, "wnd->DrawAndRunGraphicsCommands(Commands, r.mtx, r.dl);",
                    "wnd->DrawAndRunGraphicsCommands(Commands, r.mtx);")
        # Nativecade prepares sm64.o2r before the game starts, so the first-run extractor never runs.
        text = swap(text, "    instance->RunExtract(argc, argv);\n", "    instance->LoadResourceFiles();\n")
    return text


# The game's code and data. config.yml, assets/ and port/ are packed by prepare-ghostship-resources.py.
for folder in ("actors", "data", "include", "levels", "lib", "sound", "src"):
    for original in (source / folder).rglob("*"):
        if not original.is_file():
            continue
        relative = original.relative_to(source).as_posix()
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if original.suffix not in {".c", ".cpp", ".h", ".hpp"}:
            shutil.copy2(original, target)
            continue
        text = adapt(relative, original.read_text(errors="surrogateescape"))
        # Preserve timestamps when an adapter hasn't changed, keeping rebuilds small.
        if not target.exists() or target.read_text(errors="surrogateescape") != text:
            target.write_text(text, errors="surrogateescape")

# Upstream's CMake writes the version strings from src/port/build.c.in.
major, minor, patch = pin["release"].split(".")
values = {"PROJECT_BUILD_NAME": "Nautilus Alfa", "PROJECT_TEAM": "Lywx",
          "CMAKE_PROJECT_VERSION_MAJOR": major, "CMAKE_PROJECT_VERSION_MINOR": minor,
          "CMAKE_PROJECT_VERSION_PATCH": patch, "CMAKE_PROJECT_GIT_BRANCH": "",
          "CMAKE_PROJECT_GIT_COMMIT_HASH": revision[:7], "CMAKE_PROJECT_GIT_COMMIT_TAG": pin["release"]}
build = re.sub(r"@(\w+)@", lambda match: values[match[1]], (source / "src/port/build.c.in").read_text())
target = destination / "src/port/build.c"
if not target.exists() or target.read_text() != build:
    target.write_text(build)
print(f"Prepared Ghostship {pin['release']} in {destination}")
