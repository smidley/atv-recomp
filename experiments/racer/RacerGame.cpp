// Starts Star Wars Episode I: Racer from Nativecade's library (docs/GAME_SWITCHING.md). Its game code
// and audio microcode run through experiments/n64interp from the ROM in memory.
#include <TargetConditionals.h>
#include <cstdio>
#include <memory>
#include "N64RspInterpreter.h"
#include "ultramodern/renderer_context.hpp"

int NativecadeRacerMain(int argc, char **argv);   // Racer's main.cpp, renamed by CMakeLists.txt
extern "C" void n64interp_register_game(void);    // generated by scripts/generate-n64interp.py

// libultra's audio microcode, which Racer's main.cpp runs for each audio task.
RspExitReason aspMain(uint8_t *rdram, uint32_t ucode_addr) { return n64interp_rsp_run(rdram, ucode_addr); }

#if TARGET_OS_SIMULATOR
// RT64 can't draw in the tvOS simulator. With SWE1R_HEADLESS_SMOKE=1, Racer's frontend uses this
// renderer instead (prepare-racer.py), so its game code and audio can be checked there.
namespace {
class HeadlessRenderer final : public ultramodern::renderer::RendererContext {
public:
    HeadlessRenderer() {
        setup_result = ultramodern::renderer::SetupResult::Success;
        chosen_api = ultramodern::renderer::GraphicsApi::Auto;
    }
    bool valid() override { return true; }
    bool update_config(const ultramodern::renderer::GraphicsConfig &, const ultramodern::renderer::GraphicsConfig &) override {
        return true;
    }
    void enable_instant_present() override {}
    void send_dl(const OSTask *) override {
        if (++display_lists % 300 == 0) std::printf("[racer] %d display lists\n", display_lists);
    }
    void send_dummy_workload(uint32_t) override {}
    void update_screen() override {}
    void shutdown() override {}
    uint32_t get_display_framerate() const override { return 60; }
    float get_resolution_scale() const override { return 1.0f; }

private:
    int display_lists = 0;
};
} // namespace

std::unique_ptr<ultramodern::renderer::RendererContext> nativecade_headless_renderer(uint8_t *,
    ultramodern::renderer::WindowHandle, bool) {
    return std::make_unique<HeadlessRenderer>();
}
#endif

int NativecadeRunEpisodeOneRacer(int, char **) {
    // Racer prints why it stops just before returning; keep those lines when stdout is a file.
    setvbuf(stdout, nullptr, _IOLBF, 0);
    // The libultra functions the runtime replaces, before any game code runs.
    n64interp_register_game();
    // --play skips Racer's launcher window; its frontend finds the ROM in the game folder.
    char name[] = "racer", play[] = "--play";
    char *arguments[] = {name, play, nullptr};
    return NativecadeRacerMain(2, arguments);
}
