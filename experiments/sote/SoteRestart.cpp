// Starts Shadows of the Empire from Nativecade's library (docs/GAME_SWITCHING.md).
#include <TargetConditionals.h>
#include <cstdio>
#include <cstdlib>
int NativecadeSoteMain(int argc, char **argv); // SotE's main.cpp, renamed by CMakeLists.txt
#ifdef NATIVECADE_SOTE_INTERPRETED
extern "C" void n64interp_register_game(void); // generated by scripts/generate-n64interp.py
#endif

int NativecadeRunShadowsOfTheEmpire(int, char **) {
    // SotE prints why it stops to stdout just before exiting; keep those lines when it's a file.
    setvbuf(stdout, nullptr, _IOLBF, 0);
#ifdef NATIVECADE_SOTE_INTERPRETED
    // The libultra functions the runtime replaces, and SotE's hooks, before any game code runs.
    n64interp_register_game();
#endif
    // SotE reads any argument as a ROM path; it finds the prepared ROM in the game folder instead.
    char name[] = "sote", headless[] = "--headless-smoke";
    char *arguments[] = {name, nullptr, nullptr};
#if TARGET_OS_SIMULATOR
    // SOTE_HEADLESS_SMOKE runs upstream's smoke test, which plays without RT64 (the simulator's GPU
    // can't run it) for SOTE_SMOKE_VIS frames, so game code and audio can be checked here.
    if (std::getenv("SOTE_HEADLESS_SMOKE")) arguments[1] = headless;
#endif
    return NativecadeSoteMain(arguments[1] ? 2 : 1, arguments);
}
